#!/usr/bin/env python3
"""Render rules/*.md (source of truth, Cursor-style frontmatter; README.md skipped) into each agent's format.

  Cursor      -> .cursor/rules/<rule>.mdc  (frontmatter: description, globs, alwaysApply)
  Claude Code -> CLAUDE.md                 (@-imports of rules/*.md)
  Codex/other -> AGENTS.md reads rules/ directly; no generated file needed.

Usage: render_rules.py [--out DIR] [--check]
  --out    write into DIR instead of the repo root (used by smoke tests)
  --check  fail if committed outputs differ from a fresh render
"""
import argparse, json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FM = re.compile(r"\A---\n(.*?)\n---\n", re.S)
HEADER = "<!-- Generated by scripts/render_rules.py from rules/. Do not edit. -->"


def rule_files(root):
    """Rule sources: rules/*.md except README.md."""
    return sorted(p for p in (root / "rules").glob("*.md") if p.name != "README.md")


def split(text, slug):
    """Return (description, globs, alwaysApply, body) from a rule's frontmatter."""
    m = FM.match(text)
    meta = {}
    if m:
        for line in m.group(1).splitlines():
            k, _, v = line.partition(":")
            meta[k.strip()] = v.strip()
        text = text[m.end():]
    globs = meta.get("globs", "")
    if globs.startswith("["):  # YAML/JSON list -> Cursor's comma-separated form
        globs = ",".join(json.loads(globs))
    always = meta.get("alwaysApply", "true" if not globs else "false").lower() == "true"
    desc = meta.get("description") or next(
        (l[2:].strip() for l in text.splitlines() if l.startswith("# ")), slug)
    return desc, globs, always, text


def render(root):
    rules = rule_files(root)
    out = {}
    for r in rules:
        desc, globs, always, body = split(r.read_text(), r.stem)
        fm = ["---", f"description: {desc}", f"globs: {globs}",
              f"alwaysApply: {'true' if always else 'false'}", "---", HEADER, ""]
        out[f".cursor/rules/{r.stem}.mdc"] = "\n".join(fm) + body
    imports = "\n".join(f"@rules/{r.name}" for r in rules)
    out["CLAUDE.md"] = f"# CLAUDE.md\n\n{HEADER}\n\nSee AGENTS.md for the team model.\n\n{imports}\n"
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=pathlib.Path, default=ROOT)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    files = render(ROOT)
    if a.check:
        stale = [p for p, c in files.items()
                 if not (ROOT / p).exists() or (ROOT / p).read_text() != c]
        existing = {f".cursor/rules/{p.name}" for p in (ROOT / ".cursor/rules").glob("*.mdc")}
        stale += sorted(existing - files.keys())
        for p in stale:
            print("STALE", p)
        print(f"{len(stale)} stale file(s); run scripts/render_rules.py" if stale else "rules render up to date")
        sys.exit(1 if stale else 0)
    for p, c in files.items():
        dest = a.out / p
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(c)
        print("wrote", dest)


if __name__ == "__main__":
    main()
